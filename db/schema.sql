-- Database schema for the Library Loan App (local dev only).
--
-- This matches the tables Hibernate creates from the JPA entities
-- (User, Loan, Reservation) with spring.jpa.hibernate.ddl-auto=update.
-- The backend still creates the schema by itself; this file just lets you
-- create the tables without starting the backend, e.g. before running seed.sql.
--
-- Run it with:
--   docker compose exec -T db psql -U library -d library < db/schema.sql
--   docker compose exec -T db psql -U library -d library < db/seed.sql
--
-- "IF NOT EXISTS" makes it safe to run when the tables already exist.

BEGIN;

-- User entity
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(20)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL
);

-- Loan entity (returned_on IS NULL = active loan)
CREATE TABLE IF NOT EXISTS loans (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    work_id     VARCHAR(20)  NOT NULL,
    title       VARCHAR(500) NOT NULL,
    borrowed_on DATE         NOT NULL,
    due_on      DATE         NOT NULL,
    renew_count INTEGER      NOT NULL,
    returned_on DATE,
    fee_kr      INTEGER      NOT NULL,
    fee_paid    BOOLEAN      NOT NULL
);

-- Reservation entity (status stored as text, @Enumerated(EnumType.STRING))
CREATE TABLE IF NOT EXISTS reservations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    work_id    VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    status     VARCHAR(10)  NOT NULL CHECK (status IN ('ACTIVE', 'FULFILLED', 'CANCELLED'))
);

COMMIT;
